// Variables
//
// Definition of Variables
// Variables are named places to store data (like numbers, text, or true/false).
// They let programs remember values and use them later.
//
// Why Variables Are Important
// Variables make code flexible: we can store user input, remember totals, and
// update values as the program runs.
//
// How many variables are there and what are they
// In JavaScript we commonly use three ways to create variables:
// - var  (older style)
// - let  (block-scoped, recommended for changeable values)
// - const (block-scoped, for values that should not change)
//
// Why We Need Variables in Programming
// Variables let us keep and change data, perform calculations, and pass values
// between parts of a program (for example, from a form to a shopping cart).
//
// Real-Life Analogy of Variables
// A variable is like a labeled jar. You put something in the jar (a value) and
// you can read or change it later by using the label.
//
// How Variables Help Store Data
// - Save user answers from forms
// - Count items in a cart
// - Store configuration values (like tax rate)
//
// Common Uses of Variables
// - Storing user names and emails
// - Tracking shopping cart totals and quantities
// - Holding session or login state
//
// Basic Example of Storing Data
let userName = "Anita"; // store a user's name
console.log(userName);
// Output
// Anita
// Explanation: we saved text in `userName` and printed it.
//
// Brief introduction to each (1-2 lines only)
// var: old way to declare variables. You will see it in older code.
// let: modern variable for values that change (recommended when value will update).
// const: for values that should not change after they are set.
// Each of these is explained in detail in separate files: var.js, let.js, const.js
//
// Real-world examples where variables are used
// - Login System: store the entered username and a flag for authenticated state
// - E-commerce Website: store cart items, quantities, and total price
// - Banking Application: store account balance and transaction amounts
// - Employee Management System: store employee name, id, and role
//
// Summary
// Variables are the basic building blocks to hold and change data in programs.
