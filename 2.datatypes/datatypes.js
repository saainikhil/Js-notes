// Data Types
//
// Definition of Data Types
// Data types define what kind of value is stored in a variable: text, numbers,
// true/false, and more. They tell JavaScript how to work with the value.
//
// Why Data Types Are Important
// Knowing the data type helps prevent errors and allows correct operations
// (for example, adding numbers vs joining text).
//
// How many datatypes are there and what are they
// JavaScript has several data types. The most common beginner ones are:
// - String  (text)
// - Number  (numeric values)
// - Boolean (true or false)
// There are others (null, undefined, objects, arrays, functions) covered later.
//
// Why JavaScript Needs Data Types
// Data types let JavaScript choose the right operations and store the value
// efficiently in memory.
//
// Relationship Between Variables and Data Types
// A variable is a container; the data type tells us what is inside the container.
// For example, `let x = "hi";` stores a string inside `x`.
//
// How JavaScript Stores Different Kinds of Data
// - Strings are stored as text (characters)
// - Numbers are stored as numeric values (integers or decimals)
// - Booleans store true/false decisions
//
// Explain that data types tell JavaScript what kind of value is stored
// The type guides allowed operations: you can add numbers, but adding strings
// will concatenate (join) them as text.
//
// Basic examples of different values
let userName = "Riya"; // string example
let price = 499;       // number example
let isLoggedIn = false; // boolean example
console.log(userName, price, isLoggedIn);
// Output
// Riya 499 false
//
// Brief introduction to:String, Number, Boolean
// String: stores text such as usernames or product names. See string.js for details.
// Number: stores numeric values like prices and quantities. See numbers.js for details.
// Boolean: stores true/false values used for checks (like login status). See boolean.js.
// Each of these is explained in separate files.
//
// Real-world examples
// - User Name: stored as a String
// - Product Price: stored as a Number
// - Login Status: stored as a Boolean (true if logged in)
// - Shopping Cart: item names (strings), quantities (numbers), and selection flags (booleans)
// - Banking Application: balances and transaction amounts as Numbers, account active flag as Boolean
//
// Summary
// Data types are essential to understand before working with variables. Open the
